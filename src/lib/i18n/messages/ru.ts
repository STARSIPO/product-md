/**
 * Widens the `as const` literal types to plain `string`.
 *
 * Without this, `Dictionary` would demand the *exact Russian sentence* at every key,
 * so a translated dictionary could never satisfy it. The key structure is preserved,
 * which is the part that must not drift between locales.
 */
type Widen<T> = T extends string ? string : { [K in keyof T]: Widen<T[K]> }

export type Dictionary = Widen<typeof ru>
