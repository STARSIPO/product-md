/**
 * Static/legal content, Russian.
 *
 * This file is the single source of truth for the wording of the public documents:
 * terms, privacy, publication rules, security, help, contacts and the partners page.
 * Components never hardcode a sentence — they render what is written here.
 *
 * `ro.ts` is typed against `typeof ru`, so removing or renaming anything below turns
 * into a compile error in the Romanian file instead of a silently untranslated page.
 *
 * Anything the owner still has to supply (legal entity, IDNO, address, phone, support
 * hours) is written as an explicit `PLACEHOLDER` string and listed in PLACEHOLDERS.md.
 * Inventing a company name or a phone number here would be worse than admitting the
 * gap: a wrong contact in a legal document is a liability, an obvious placeholder is a
 * task.
 */

export const PLACEHOLDER = 'PLACEHOLDER'

export interface LegalSection {
  heading: string
  paragraphs: string[]
  list?: string[]
}

export interface LegalDocument {
  /** <h1> and <title>. */
  title: string
  /** Meta description; one sentence, no marketing filler. */
  description: string
  /** ISO date (YYYY-MM-DD); rendered through the locale formatter. */
  updated: string
  /** Lead paragraph above the table of contents. */
  intro: string
  sections: LegalSection[]
}

export interface FaqItem {
  question: string
  answer: string[]
}

export interface FaqGroup {
  title: string
  items: FaqItem[]
}

export interface HelpDocument {
  title: string
  description: string
  updated: string
  intro: string
  groups: FaqGroup[]
  /** Closing block: what to do when the FAQ did not answer the question. */
  outro: LegalSection
}

export interface ContactChannel {
  label: string
  /** Either a real value or the PLACEHOLDER marker. */
  value: string
  note: string
  /** True when `value` must be replaced by the owner before launch. */
  isPlaceholder: boolean
  /** Rendered as a link when the value is a real address/number. */
  hrefPrefix?: 'mailto:' | 'tel:'
}

export interface ContactsDocument {
  title: string
  description: string
  updated: string
  intro: string
  placeholderNotice: LegalSection
  channelsHeading: string
  channels: ContactChannel[]
  sections: LegalSection[]
  linksHeading: string
  links: { label: string; description: string; target: 'help' | 'rules' | 'security' | 'privacy' }[]
}

export interface LegalUiLabels {
  tableOfContents: string
  onThisPage: string
  placeholderBadge: string
  placeholderValue: string
  faqHint: string
}

export interface LegalContent {
  ui: LegalUiLabels
  terms: LegalDocument
  privacy: LegalDocument
  rules: LegalDocument
  security: LegalDocument
  help: HelpDocument
  contacts: ContactsDocument
  partners: LegalDocument
}

